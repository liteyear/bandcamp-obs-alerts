const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawn } = require('node:child_process');
const http = require('node:http');
test('local helper protects settings and broadcasts queued alerts without credentials', async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'bca-test-'));
  const port = 19000 + Math.floor(Math.random() * 5000);
  const base = `http://127.0.0.1:${port}`;
  const child = spawn(process.execPath, [path.join(__dirname, '..', 'server.cjs')], { env: { ...process.env, BCA_DEMO: '1', BCA_PORT: String(port), BCA_DATA_DIR: dir }, stdio: 'ignore' });
  t.after(() => { child.kill('SIGTERM'); fs.rmSync(dir, { recursive: true, force: true }); });
  let ready = false;
  for (let i = 0; i < 100; i++) { try { const response = await fetch(base + '/health'); if (response.ok) { ready = true; break; } } catch {} await new Promise(r => setTimeout(r, 50)); }
  assert.ok(ready);
  const key = new URLSearchParams(new URL(fs.readFileSync(path.join(dir, 'control-url.txt'), 'utf8')).hash.slice(1)).get('key');
  const get = route => fetch(base + route, { headers: { 'x-admin-key': key } });
  const post = (route, data = {}, extra = {}) => fetch(base + '/api/' + route, { method: 'POST', headers: { 'x-admin-key': key, 'Content-Type': 'application/json', ...extra }, body: JSON.stringify(data) });
  assert.equal((await fetch(base + '/api/status')).status, 403);
  assert.equal((await fetch(base + '/settings.json')).status, 404);
  assert.equal((await fetch(base + '/events?key=wrong')).status, 403);
  assert.equal((await post('test', {}, { Origin: 'https://evil.test' })).status, 403);
  const spoofedHostStatus = await new Promise((resolve, reject) => { http.get(base + '/health', { headers: { Host: 'evil.test' } }, response => { response.resume(); resolve(response.statusCode); }).on('error', reject); });
  assert.equal(spoofedHostStatus, 403);
  const state = await (await get('/api/status')).json();
  const viewer = new URLSearchParams(new URL(state.overlayUrl).hash.slice(1)).get('key');
  assert.notEqual(viewer, key);
  assert.equal((await fetch(base + '/api/status', { headers: { 'x-admin-key': viewer } })).status, 403);
  const abort = new AbortController();
  const stream = await fetch(base + '/events?key=' + viewer, { signal: abort.signal });
  const reader = stream.body.getReader();
  const initial = new TextDecoder().decode((await reader.read()).value);
  assert.ok(initial.includes('data: null'));
  assert.equal((await post('test')).status, 200);
  const alert = new TextDecoder().decode((await reader.read()).value);
  assert.ok(alert.includes('Example Album'));
  assert.ok(alert.includes('"test":true'));
  assert.ok(!alert.includes('@'));
  await post('test');
  assert.equal((await (await get('/api/status')).json()).queued, 1);
  await post('settings', { artistName: 'Example Artist', duration: 1, showBuyer: false, showAmount: false });
  const updated = await (await get('/api/status')).json();
  assert.equal(updated.duration, 5); assert.equal(updated.showBuyer, false);
  assert.equal((await post('connect', { email: 'a@example.test', password: 'abcdefghijklmnop' })).status, 400);
  abort.abort();
  await post('stop');
  await new Promise(resolve => child.once('exit', resolve));
});
